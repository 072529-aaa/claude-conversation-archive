  await page.getByRole('button', { name: '关闭窗口', exact: true }).click();
  assert.equal(await page.locator('article.archive-message').count(), 5);
  await page.getByText('正文结束标记：已完整保留。', { exact: true }).waitFor();
  assert.equal(await page.locator('.msg-markdown table').count(), 1);
  assert.ok(await page.locator('.katex').count() >= 2);
  assert.equal(await page.locator('.msg-markdown .msg-code pre').first().innerText().then(text => text.includes('const restore')), true);
  assert.equal(await page.evaluate(() => window.__ARCHIVE_XSS_TEST__), undefined);
