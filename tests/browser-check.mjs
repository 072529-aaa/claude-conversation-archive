  assert.match(await readFile(await attachmentDownload.path(), 'utf8'), /附件文本完整性标记/);
  await page.getByRole('button', { name: '导出', exact: true }).click();
  const jsonPending = page.waitForEvent('download');
  await page.getByRole('button', { name: '完整原始 JSON', exact: true }).click();
  const jsonDownload = await jsonPending;
  const downloadedConversation = JSON.parse(await readFile(await jsonDownload.path(), 'utf8'));
  assert.equal(downloadedConversation.chat_messages.length, 5);
  assert.match(JSON.stringify(downloadedConversation), /未知类型完整性标记/);
  check('Footnotes preserve conversation route; original attachment and full conversation exports work');
  await page.locator('.msg-thinking summary').click();
  await page.getByText('这是显式包含在测试导出中的思考块，用于验证完整展示。', { exact: true }).waitFor();
  await page.locator('.msg-tool').first().locator('summary').click();
  assert.match(await page.locator('.msg-tool').first().innerText(), /工具检索唯一关键词/);
  await page.locator('.msg-unknown summary').click();
  assert.match(await page.locator('.msg-unknown').innerText(), /未知类型完整性标记/);
  await page.locator('.msg-extracted summary').click();
  assert.match(await page.locator('.msg-extracted').innerText(), /附件文本完整性标记/);
  assert.equal(await page.locator('.msg-missing-file').count(), 1);
  assert.equal(await page.locator('.msg-asset-media img').count(), 1);
  check('Thinking, tools, unknown blocks, extracted attachment text and missing-file warning retained');
  await page.locator('.main-scroll').evaluate(element => element.scrollTop = 0);
