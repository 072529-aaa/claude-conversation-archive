  await page.getByRole('button', { name: '静态预览', exact: true }).click();
  await page.frameLocator('.artifact-frame').getByRole('heading', { name: '静态 Artifact' }).waitFor();
  assert.equal(await page.evaluate(() => window.__ARTIFACT_XSS_TEST__), undefined);
  await page.getByRole('button', { name: '关闭窗口', exact: true }).click();
  check('Artifact source preserved; sandboxed static preview prevents scripts');
  await page.getByRole('button', { name: '收藏对话', exact: true }).click();
  await page.getByRole('button', { name: '搜索对话 Ctrl K' }).click();
